import { z } from 'zod';
import { id, screenId as screenIdSchema, timezone } from '../../config.js';
import { screenOverrideSchema } from '../../services/settingsStore.js';
import { listPhotos } from '../../services/photos.js';
import { pruneLinkIcons } from '../../services/linkIcons.js';

const addDisplaySchema = z.strictObject({
  title: z.string().min(1).max(60),
  timezone,
  // Optional: otherwise made from the title ("Parents' kitchen" -> parents-kitchen).
  id: screenIdSchema.optional(),
  // Optional: start from another display's look (layout, text size, rotation...).
  copyLookFrom: id.optional(),
});

/** "Parents' Kitchen!" -> "parents-kitchen" */
function slugify(text) {
  return (
    text
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 30) || 'display'
  );
}

/**
 * Create, change and delete displays.
 *
 * @param {import('fastify').FastifyInstance} app
 * @param {ReturnType<import('./context.js').createAdminContext>} ctx
 */
export default function registerDisplayRoutes(app, { services, iconsDir, secured, applySettings, problemsFrom }) {
  const { settingsStore, live } = services;

  app.post('/api/admin/screens', secured, async (req, reply) => {
    const parsed = addDisplaySchema.safeParse(req.body);
    if (!parsed.success) return reply.code(400).send({ error: 'invalid display', problems: problemsFrom(parsed.error) });

    const { title, timezone: tz, copyLookFrom } = parsed.data;
    const taken = Object.keys(live.get().screens);

    let newId = parsed.data.id ?? slugify(title);
    if (parsed.data.id && taken.includes(newId)) {
      return reply.code(409).send({ error: `there is already a display called "${newId}"` });
    }
    // Made-up ids get a number added until they are free (and not reserved).
    for (let n = 2; !parsed.data.id && (taken.includes(newId) || !screenIdSchema.safeParse(newId).success); n++) {
      newId = `${slugify(title)}-${n}`.slice(0, 34);
    }

    let look = {};
    if (copyLookFrom) {
      const source = live.get().screens[copyLookFrom];
      if (!source) return reply.code(404).send({ error: 'unknown display to copy from' });
      const { layout, weeks, weekStart, clock, fontScale, rotate } = source;
      look = { layout, weeks, weekStart, clock, fontScale, rotate, photos: { interval: source.photos.interval } };
    }

    const failed = await applySettings(reply, (s) => {
      s.displays[newId] = { title, timezone: tz, ...look, calendars: [], photos: look.photos ?? {} };
    });
    return failed ?? { ok: true, id: newId };
  });

  // Deleting a display keeps its photo files on disk (they are yours); only the settings go.
  app.delete('/api/admin/screens/:id', secured, async (req, reply) => {
    const displayId = req.params.id;
    if (!(displayId in settingsStore.get().displays)) {
      return reply.code(400).send({ error: 'only displays created in the dashboard can be deleted here' });
    }
    const failed = await applySettings(reply, (s) => {
      delete s.displays[displayId];
      delete s.screens[displayId];
    });
    return failed ?? { ok: true };
  });

  // Change any of a display's settings (layout, mode, links, ...). Only valid changes are kept.
  app.patch('/api/admin/screens/:id', secured, async (req, reply) => {
    const screenId = req.params.id;
    if (!live.get().screens[screenId]) return reply.code(404).send({ error: 'unknown screen' });

    // The token is generated by its own endpoint, never accepted from the browser.
    const parsed = screenOverrideSchema.omit({ token: true }).safeParse(req.body);
    if (!parsed.success) return reply.code(400).send({ error: 'invalid settings', problems: problemsFrom(parsed.error) });

    // A link may only use an uploaded picture that belongs to THIS display.
    if (parsed.data.links) {
      const uploaded = new Set(await listPhotos(iconsDir, screenId));
      const missing = parsed.data.links.find(
        (link) => link.icon.startsWith('image:') && !uploaded.has(link.icon.slice('image:'.length)),
      );
      if (missing) {
        const problems = [`the picture for "${missing.title}" is missing; upload it again`];
        return reply.code(400).send({ error: 'invalid settings', problems });
      }
    }

    const failed = await applySettings(reply, (s) => {
      s.screens[screenId] = { ...s.screens[screenId], ...parsed.data };
    });
    if (failed) return failed;

    if (parsed.data.links) await pruneLinkIcons(iconsDir, screenId, parsed.data.links);
    return { ok: true };
  });
}
